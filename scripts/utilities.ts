/**
 * Inline style → utility class mapping used to port the export's style="" attributes.
 *   npx tsx scripts/utilities.ts            regenerate styles/utilities.css from the export
 *   npx tsx scripts/utilities.ts "a:b;c:d"  print the class list for one style attribute
 * Utilities are !important so they keep the precedence the inline styles had.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const PREFIX: Record<string, string> = {
  'margin-top': 'mt', margin: 'm', 'margin-bottom': 'mb', 'margin-left': 'ml', 'margin-right': 'mr',
  display: 'd', 'font-family': 'ff', 'align-items': 'ai', gap: 'gap', 'font-style': 'fst', 'max-width': 'maxw',
  'border-bottom': 'bb', 'flex-wrap': 'fw', color: 'c', 'font-size': 'fs', 'padding-bottom': 'pb',
  'padding-top': 'pt', padding: 'p', 'border-color': 'bc', 'grid-template-columns': 'cols', 'font-weight': 'fwt',
  'text-align': 'ta', 'justify-content': 'jc', 'text-transform': 'tt', stroke: 'stroke', 'transition-delay': 'delay',
  'min-height': 'minh', 'line-height': 'lh', 'letter-spacing': 'ls', background: 'bg', 'aspect-ratio': 'ar',
  'border-top': 'bt', border: 'b', position: 'pos',
};

const FONT: Record<string, [string, string]> = {
  "'Cormorant Garamond',serif": ['serif', 'var(--font-cormorant),serif'],
  "'Julius Sans One',sans-serif": ['julius', 'var(--font-julius),sans-serif'],
  "'Jost',sans-serif": ['jost', 'var(--font-jost),sans-serif'],
};

function slug(prop: string, value: string): string {
  if (prop === 'font-family') return FONT[value][0];
  return value
    .replace(/^1px solid /, '')
    .replace(/rgba\(246,242,233,\.(\d+)\)/g, 'bone$1')
    .replace(/#77735f/gi, 'muted')
    .replace(/#4c493f/gi, 'body')
    .replace(/var\(--([a-z0-9-]+)\)/g, '$1')
    .replace(/currentColor/g, 'current')
    .replace(/(\d)?\.(\d)/g, (_, a = '', b) => `${a}p${b}`)
    .replace(/(\d)rem\b/g, '$1')
    .replace(/[^a-zA-Z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

export function parseStyle(style: string): { prop: string; value: string }[] {
  return style
    .split(';')
    .map((d) => d.trim())
    .filter(Boolean)
    .map((d) => {
      const i = d.indexOf(':');
      return { prop: d.slice(0, i).trim(), value: d.slice(i + 1).trim() };
    });
}

export function className(prop: string, value: string): string {
  const p = PREFIX[prop];
  if (!p) throw new Error(`No utility prefix for ${prop}`);
  return `${p}-${slug(prop, value)}`;
}

export const classesFor = (style: string) => parseStyle(style).map((d) => className(d.prop, d.value)).join(' ');

function generate() {
  const root = path.resolve(import.meta.dirname, '../../ocama-2.0-export');
  const decls = new Map<string, string>();
  for (const lang of ['en', 'es']) {
    for (const f of readdirSync(path.join(root, lang)).filter((f) => f.endsWith('.html'))) {
      const html = readFileSync(path.join(root, lang, f), 'utf8');
      for (const m of html.matchAll(/style="([^"]*)"/g)) {
        for (const { prop, value } of parseStyle(m[1])) {
          const v = prop === 'font-family' ? FONT[value][1] : value;
          decls.set(className(prop, value), `${prop}:${v}`);
        }
      }
    }
  }
  const css = [...decls.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([cls, decl]) => `.${cls}{${decl} !important}`)
    .join('\n');
  writeFileSync(
    path.resolve(import.meta.dirname, '../styles/utilities.css'),
    `/* Generated by scripts/utilities.ts from the export's inline styles. !important keeps inline precedence. */\n${css}\n`,
  );
  console.log(`${decls.size} utilities`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv[2]) console.log(classesFor(process.argv[2]));
  else generate();
}
